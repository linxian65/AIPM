export function clarifyPrompt(brief: string, feedback: string): string {
  const isRevision = feedback.trim().length > 0;
  return `你是 AI 产品经理的评估副驾驶。用户给出了一句模糊的 AI 功能需求。
用户需求：${brief}
${isRevision ? `这是修订轮次。以下是用户对上一版追问的回答：
${feedback}
请基于用户的回答生成新一轮追问：
- 用户已回答的问题视为已澄清，不要重复问
- 应该往更深一层追问，或者转向尚未覆盖的新维度
- 保持 8-12 条，保持问题之间不重复
- 优先追问用户在回答中透露出的、但还没说清的约束` : `生成 8-12 个关键追问，帮用户把需求想清楚。`}
追问必须覆盖的维度（整体均衡即可，不要求每个维度一条）：
- 目标用户与核心任务
- AI 的输出类型（文本 / 决策 / 动作）
- 错误代价与可容忍错误率
- 必须转人工的场景
- 数据来源、隐私与合规约束
- 成本与延迟预算
- 成功指标
- 灰度上线门槛
每条追问包含：
- question：具体的追问，一句话
- rationale：为什么重要
- priority：low / medium / high
要求：
- 中文
- 追问要具体，避免"目标用户是谁"这种万金油
- 不要重复用户已回答的问题
- 优先返回高优先级的问题`;
}
